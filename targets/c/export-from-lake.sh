#!/usr/bin/env bash
#
# Copy Lean's generated C out of lean/.lake into src/.
#
# Usage: ./export-from-lake.sh [--no-build]
#
# Authors:       Tobias Ladner
# Written:       16-August-2026
# Last update:   ---
# Last revision: ---

set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(cd "$script_dir/../.." && pwd)"
lean_dir="$repo_root/lean"
ir_dir="$lean_dir/.lake/build/ir"
dest_dir="$script_dir/src"

# Lean never deletes the C of a renamed module, so only a clean build matches the
# sources. Scoped to CORALean: a bare `lake clean` also wipes Mathlib.
if [[ "${1:-}" == "--no-build" ]]; then
  shift
else
  echo "==> lake clean CORALean && lake build"
  (cd "$lean_dir" && lake clean CORALean && lake build)
fi

if [[ ! -d "$ir_dir" ]]; then
  echo "error: $ir_dir does not exist; run 'lake build' in $lean_dir" >&2
  exit 1
fi

# Driven by the sources, so a module missing its C is an error, not a silent gap.
module_list="$(mktemp)"
trap 'rm -f "$module_list"' EXIT
(
  cd "$lean_dir"
  [[ -f CORALean.lean ]] && echo CORALean
  find CORALean -name '*.lean' | sed 's/\.lean$//'
) | sort > "$module_list"

echo "==> exporting $(wc -l < "$module_list" | tr -d ' ') modules"

rm -rf "$dest_dir"
mkdir -p "$dest_dir"

missing=0
while IFS= read -r module; do
  src="$ir_dir/$module.c"
  if [[ ! -f "$src" ]]; then
    echo "error: no generated C for module $module" >&2
    missing=1
    continue
  fi
  mkdir -p "$dest_dir/$(dirname "$module")"
  cp "$src" "$dest_dir/$module.c"
done < "$module_list"

if [[ $missing -ne 0 ]]; then
  echo "error: export incomplete" >&2
  exit 1
fi

toolchain="$(tr -d '[:space:]' < "$lean_dir/lean-toolchain")"
commit="$(git -C "$repo_root" rev-parse --short HEAD 2>/dev/null || echo unknown)"
dirty=""
git -C "$repo_root" diff --quiet 2>/dev/null || dirty=" (working tree dirty)"

cat > "$dest_dir/PROVENANCE.txt" <<EOF
Generated by Lean's C backend. Do not edit; see ../README.md.

toolchain:  $toolchain
source:     $commit$dirty
exported:   $(date -u '+%Y-%m-%d %H:%M:%S UTC')
modules:    $(wc -l < "$module_list" | tr -d ' ')
EOF

echo "==> wrote $(find "$dest_dir" -name '*.c' | wc -l | tr -d ' ') files to src/"
