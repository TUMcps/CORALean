#!/usr/bin/env python3
"""Write witnessNet.m: the random 2-input ReLU networks of CORA.cpp's NN witness search (the seeds of
witness.py, regenerated with numpy's default_rng), with the threshold t of the unsafe set
y1 - y2 <= t and the sampled input with the smallest y1 - y2, for MATLAB.

Usage: python3 witnessNets.py SEED... > witnessNet.m"""
import math
import sys

import numpy as np


def net(seed):
    rng = np.random.default_rng(seed)
    sizes = [2, int(rng.integers(4, 9)), int(rng.integers(4, 9)), 2]
    Ws = [((rng.standard_normal((sizes[k + 1], sizes[k])) / math.sqrt(sizes[k])).astype(np.float32),
           (0.5 * rng.standard_normal(sizes[k + 1])).astype(np.float32)) for k in range(3)]
    xs = rng.uniform(-1, 1, (200000, 2))
    h = xs
    for k, (W, b) in enumerate(Ws):
        h = h @ W.T.astype(np.float64) + b
        h = np.maximum(h, 0) if k < 2 else h
    diff = h[:, 0] - h[:, 1]
    t = float(np.quantile(diff, 0.002))
    return sizes, Ws, t, xs[int(np.argmin(diff))]


def mat(M):
    M = np.atleast_2d(np.asarray(M, dtype=np.float64))
    return "[" + ";".join(" ".join(f"{v:.17g}" for v in row) for row in M) + "]"


seeds = [int(s) for s in sys.argv[1:]]
print("function [W, b, t, xbad] = witnessNet(seed)")
print("% witnessNet - weights W{k}, biases b{k} of a witness network, the bound t of the unsafe set")
print("%    [1 -1]*y <= t and a sampled input xbad in it; generated by witnessNets.py, do not edit.")
print("switch seed")
for s in seeds:
    sizes, Ws, t, xb = net(s)
    print(f"  case {s} % sizes {sizes}")
    print("    W = {" + ", ".join(mat(W) for W, _ in Ws) + "};")
    print("    b = {" + ", ".join(mat(bb.reshape(-1, 1)) for _, bb in Ws) + "};")
    print(f"    t = {t:.17g}; xbad = {mat(xb.reshape(-1, 1))};")
print("  otherwise\n    error('witnessNet: no seed %d', seed);\nend\nend")
